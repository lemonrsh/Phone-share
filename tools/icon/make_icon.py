#!/usr/bin/env python3
"""Generates the launcher icon: adaptive vector layers + legacy PNG mipmaps.

One shape description is rendered both as Android vector drawables (API 26+
adaptive icon, monochrome themed icon, notification icon) and, with Pillow, as
PNGs for older Android versions. Run from the repository root:

    python3 tools/icon/make_icon.py
"""
import os

from PIL import Image, ImageDraw, ImageFilter

RES = "app/src/main/res"

GREEN_LIGHT = (34, 197, 94)     # #22C55E
GREEN_DARK = (15, 118, 110)     # #0F766E
SCREEN = (22, 163, 74)          # #16A34A
WHITE = (255, 255, 255)

# Shapes in the 108x108 adaptive-icon viewport (safe zone: circle r=33 at 54,54).
BACK_PHONE = (30, 30, 22, 40, 5)          # x, y, w, h, radius
BACK_SCREEN = (33, 35, 16, 30, 2.5)
FRONT_SHADOW = (51.5, 38, 24, 42, 5.5)
FRONT_PHONE = (50, 36, 24, 42, 5.5)
FRONT_SCREEN = (53, 41.5, 18, 30, 2.5)
SPEAKER = (59, 38.4, 6, 1.6, 0.8)
PLAY = [(59, 50.5), (59, 62.5), (68.5, 56.5)]


def rr_path(x, y, w, h, r):
    return ("M{:g},{:g}h{:g}a{:g},{:g} 0,0 1,{:g},{:g}v{:g}a{:g},{:g} 0,0 1,{:g},{:g}"
            "h{:g}a{:g},{:g} 0,0 1,{:g},{:g}v{:g}a{:g},{:g} 0,0 1,{:g},{:g}z").format(
        x + r, y, w - 2 * r, r, r, r, r, h - 2 * r, r, r, -r, r,
        -(w - 2 * r), r, r, -r, -r, -(h - 2 * r), r, r, r, -r)


def poly_path(points):
    head, *rest = points
    return "M{:g},{:g}".format(*head) + "".join("L{:g},{:g}".format(*p) for p in rest) + "z"


def vector(paths, size=108, viewport=108, extra_ns=False):
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if extra_ns else ""
    body = "\n".join(paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/icon/make_icon.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
            '    android:width="{s}dp"\n    android:height="{s}dp"\n'
            '    android:viewportWidth="{v}"\n    android:viewportHeight="{v}">\n{body}\n</vector>\n'
            ).format(ns=ns, s=size, v=viewport, body=body)


def path(data, color, alpha=None):
    fill = color if alpha is None else "#{:02X}{}".format(alpha, color.lstrip("#")[-6:])
    return '    <path\n        android:fillColor="{}"\n        android:pathData="{}" />'.format(fill, data)


def write(rel, content):
    full = os.path.join(RES, rel)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w") as f:
        f.write(content)


def write_vectors():
    # Background: diagonal green gradient with a soft highlight.
    gradient_bg = vector([
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient\n'
        '                android:type="linear"\n'
        '                android:startX="0" android:startY="0"\n'
        '                android:endX="108" android:endY="108">\n'
        '                <item android:offset="0" android:color="#FF22C55E" />\n'
        '                <item android:offset="1" android:color="#FF0F766E" />\n'
        '            </gradient>\n'
        '        </aapt:attr>\n'
        '    </path>',
        path("M0,0h108v46c-20,-12 -60,-14 -108,10z", "#FFFFFF", 0x14),
    ], extra_ns=True)
    write("drawable-v24/ic_launcher_background.xml", gradient_bg)
    # API 21-23 cannot draw vector gradients: flat fallback (only used by the v26 adaptive icon anyway).
    write("drawable/ic_launcher_background.xml", vector([path("M0,0h108v108h-108z", "#FF16A34A")]))

    foreground = vector([
        path(rr_path(*BACK_PHONE), "#FFFFFF", 0x66),
        path(rr_path(*BACK_SCREEN), "#0F766E", 0x55),
        path(rr_path(*FRONT_SHADOW), "#000000", 0x33),
        path(rr_path(*FRONT_PHONE), "#FFFFFFFF"),
        path(rr_path(*FRONT_SCREEN), "#FF16A34A"),
        path(rr_path(*SPEAKER), "#FF16A34A"),
        path(poly_path(PLAY), "#FFFFFFFF"),
    ])
    write("drawable/ic_launcher_foreground.xml", foreground)

    # Themed (monochrome) icon: the system tints it, alpha gives the depth.
    mono = vector([
        path(rr_path(*BACK_PHONE), "#000000", 0x80),
        # Front phone as an outline (evenOdd cut-out of the screen) with the play mark inside.
        '    <path\n        android:fillColor="#FF000000"\n        android:fillType="evenOdd"\n'
        '        android:pathData="{}" />'.format(rr_path(*FRONT_PHONE) + rr_path(*FRONT_SCREEN)),
        path(poly_path(PLAY), "#FF000000"),
    ])
    write("drawable/ic_launcher_monochrome.xml", mono)

    # Notification icon (24dp, white silhouette): reuse the front phone, scaled to fill.
    s = 24 / 50.0
    ox, oy = 40, 32
    def t(r):
        x, y, w, h, rad = r
        return ((x - ox) * s + 0.0, (y - oy) * s, w * s, h * s, rad * s)
    back = t(BACK_PHONE)
    front = t(FRONT_PHONE)
    screen = t(FRONT_SCREEN)
    play = [((x - ox) * s, (y - oy) * s) for x, y in PLAY]
    note = vector([
        path(rr_path(*back), "#FFFFFF", 0x80),
        '    <path\n        android:fillColor="#FFFFFFFF"\n        android:fillType="evenOdd"\n'
        '        android:pathData="{}" />'.format(rr_path(*front) + rr_path(*screen)),
        path(poly_path(play), "#FFFFFFFF"),
    ], size=24, viewport=24)
    write("drawable/ic_notification.xml", note)

    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@drawable/ic_launcher_background" />\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
                '</adaptive-icon>\n')
    write("mipmap-anydpi-v26/ic_launcher.xml", adaptive)
    write("mipmap-anydpi-v26/ic_launcher_round.xml", adaptive)


# ---------------------------------------------------------------- PNG rendering

def render(size, round_shape):
    ss = 4
    big = size * ss
    # Legacy icons show the central 72x72 of the 108 viewport, inset a little like system icons.
    inset = big * 0.04
    span = big - 2 * inset
    scale = span / 72.0

    def m(x, y):
        return (inset + (x - 18) * scale, inset + (y - 18) * scale)

    def rect(r):
        x, y, w, h, rad = r
        x0, y0 = m(x, y)
        x1, y1 = m(x + w, y + h)
        return [x0, y0, x1, y1], rad * scale

    # Gradient background.
    bg = Image.new("RGB", (big, big))
    px = bg.load()
    for yy in range(big):
        for xx in range(big):
            t = (xx + yy) / (2.0 * (big - 1))
            px[xx, yy] = tuple(int(GREEN_LIGHT[i] + (GREEN_DARK[i] - GREEN_LIGHT[i]) * t) for i in range(3))
    icon = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    mask = Image.new("L", (big, big), 0)
    md = ImageDraw.Draw(mask)
    if round_shape:
        md.ellipse([inset, inset, big - inset, big - inset], fill=255)
    else:
        md.rounded_rectangle([inset, inset, big - inset, big - inset], radius=span * 0.22, fill=255)
    icon.paste(bg, (0, 0), mask)

    # Drop shadow of the whole tile for legacy launchers.
    shadow = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    shadow.paste((0, 0, 0, 60), (0, int(big * 0.012)), mask)
    shadow = shadow.filter(ImageFilter.GaussianBlur(big * 0.01))
    base = Image.alpha_composite(shadow, icon)

    layer = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    box, rad = rect(BACK_PHONE)
    d.rounded_rectangle(box, radius=rad, fill=(255, 255, 255, 102))
    box, rad = rect(BACK_SCREEN)
    d.rounded_rectangle(box, radius=rad, fill=(15, 118, 110, 85))
    base = Image.alpha_composite(base, layer)

    layer = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    box, rad = rect(FRONT_SHADOW)
    d.rounded_rectangle(box, radius=rad, fill=(0, 0, 0, 70))
    layer = layer.filter(ImageFilter.GaussianBlur(big * 0.008))
    base = Image.alpha_composite(base, layer)

    layer = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    box, rad = rect(FRONT_PHONE)
    d.rounded_rectangle(box, radius=rad, fill=WHITE + (255,))
    box, rad = rect(FRONT_SCREEN)
    d.rounded_rectangle(box, radius=rad, fill=SCREEN + (255,))
    box, rad = rect(SPEAKER)
    d.rounded_rectangle(box, radius=rad, fill=SCREEN + (255,))
    d.polygon([m(x, y) for x, y in PLAY], fill=WHITE + (255,))
    base = Image.alpha_composite(base, layer)

    # Keep everything inside the tile shape.
    out = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    full_mask = Image.new("L", (big, big), 0)
    full_mask.paste(255, (0, 0), mask)
    shadow_alpha = shadow.split()[3]
    out = Image.composite(base, Image.alpha_composite(Image.new("RGBA", (big, big), (0, 0, 0, 0)), shadow),
                          full_mask)
    del shadow_alpha
    return out.resize((size, size), Image.LANCZOS)


def write_pngs():
    sizes = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    for density, size in sizes.items():
        folder = os.path.join(RES, "mipmap-" + density)
        os.makedirs(folder, exist_ok=True)
        render(size, False).save(os.path.join(folder, "ic_launcher.png"), optimize=True)
        render(size, True).save(os.path.join(folder, "ic_launcher_round.png"), optimize=True)
    # Large preview (README / store listing).
    os.makedirs("docs", exist_ok=True)
    render(512, False).save("docs/icon-512.png", optimize=True)


if __name__ == "__main__":
    write_vectors()
    write_pngs()
    print("Icon written.")
